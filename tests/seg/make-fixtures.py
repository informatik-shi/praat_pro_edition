from pathlib import Path
root = Path('tests/seg')
def write(name, rows, rate=1000, bps=2, count=None, codec='utf-8'):
    text = '[PARAMETERS]\nSAMPLING_FREQ=%d\nBYTE_PER_SAMPLE=%d\nCODE=0\nN_CHANNEL=1\nN_LABEL=%d\n[LABELS]\n' % (rate,bps,len(rows) if count is None else count)
    text += ''.join(f'{offset},2,{label}\n' for offset,label in rows)
    (root/name).write_bytes(text.replace('\n','\r\n').encode(codec))
